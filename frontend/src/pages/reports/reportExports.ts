import { jsPDF } from "jspdf";
import { autoTable } from "jspdf-autotable";
import * as XLSX from "xlsx";
import type { RoleReportResult } from "../../services/reportsApi";
import { reportLogo } from "./reportLogo";
import { downloadWorkbook } from "./reportWorkbook";
export type ExportFormat = "csv" | "xlsx" | "pdf" | "print";

export const reportLabel = (value: string) =>
  value
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/_/g, " ")
    .replace(/^./, (c) => c.toUpperCase());

export function financialCell(
  value: string | number | null,
): string | number | null {
  if (value == null) return null;
  if (typeof value === "number") return value;
  return value.trim() !== "" && Number.isFinite(Number(value))
    ? Number(value)
    : value;
}

export function formatFinancialValue(value: string | number | null): string {
  const cell = financialCell(value);
  return cell == null
    ? "Unavailable"
    : typeof cell === "number"
      ? cell.toLocaleString(undefined, { maximumFractionDigits: 2 })
      : cell;
}

export const reportNumber = (value: number) =>
  value.toLocaleString("en-US", { maximumFractionDigits: 2 });

function reportInformation(report: RoleReportResult) {
  const { title, metadata, summary } = report;
  return [
    ["Brand", "URUTIX"],
    ["Report", title],
    ["Category", reportLabel(report.category)],
    ["Period", metadata.period],
    ["Date basis", metadata.dateBasis || "Record creation date"],
    ...(metadata.balanceBasis
      ? [["Balance basis", metadata.balanceBasis]]
      : []),
    [
      "Generated",
      new Date(metadata.generatedAt)
        .toISOString()
        .replace("T", " ")
        .slice(0, 16) + " UTC",
    ],
    ["Generated by", metadata.generatedBy],
    [
      "Tenant",
      metadata.tenantName ||
        (metadata.tenantId === "*" ? "All tenants" : "Tenant unavailable"),
    ],
    ["Records", report.total],
    ...Object.entries(metadata.filters)
      .filter(
        ([k, v]) =>
          v !== undefined &&
          !["category", "page", "pageSize", "tenantId"].includes(k),
      )
      .map(([k, v]) => [reportLabel(k), String(v)]),
    ...Object.entries(summary.metrics).map(([k, v]) => [k, reportNumber(v)]),
    ...summary.breakdowns.map((b) => [
      `${b.dimension}: ${b.key}`,
      `${b.count} records${b.completed === undefined ? "" : `; ${b.completed} completed`}`,
    ]),
    ...summary.statuses.map((s) => [s.status, s.count]),
    ...summary.amounts.map((a) => [
      String(a.currency || "Unspecified") + " / " + String(a.status || ""),
      Object.entries(a)
        .filter(([k]) => k !== "currency" && k !== "status")
        .map(([k, v]) => `${reportLabel(k)}: ${v == null ? "Unavailable" : v}`)
        .join("; "),
    ]),
  ];
}

export function createReportPdf(report: RoleReportResult) {
  const { title, headers, rows } = report;
  const doc = new jsPDF({
    orientation: headers.length > 6 ? "landscape" : "portrait",
    unit: "pt",
    format: "a4",
  });
  const width = doc.internal.pageSize.getWidth();
  const margin = 36;
  const contentWidth = width - margin * 2;
  const blue: [number, number, number] = [28, 65, 101];
  const teal: [number, number, number] = [53, 139, 155];
  const table = (
    heading: string[],
    body: (string | number)[][],
    startY: number,
    dense = false,
  ) => {
    autoTable(doc, {
      startY,
      head: [heading],
      body,
      margin: { top: 110, bottom: 40, left: margin, right: margin },
      styles: {
        font: "helvetica",
        fontSize: dense ? 8 : 9,
        cellPadding: dense ? 4 : 5,
        textColor: [51, 65, 85],
        overflow: "linebreak",
      },
      headStyles: {
        fillColor: blue,
        textColor: [255, 255, 255],
        fontStyle: "bold",
      },
      rowPageBreak: "avoid",
      alternateRowStyles: { fillColor: [245, 248, 251] },
    });
    return (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable
      .finalY;
  };
  const section = (label: string, y: number) => {
    if (y > doc.internal.pageSize.getHeight() - 100) {
      doc.addPage();
      y = 115;
    }
    doc.setFontSize(11);
    doc.setTextColor(...blue);
    doc.setFont("helvetica", "bold");
    doc.text(label, margin, y);
    return y + 12;
  };
  // Keep report details separate from metrics and participant activity.
  const details = reportInformation(report)
    .slice(1)
    .filter(([key]) =>
      [
        "Report",
        "Period",
        "Date basis",
        "Balance basis",
        "Generated",
        "Generated by",
        "Tenant",
      ].includes(String(key)),
    );
  let y =
    table(
      ["Report details", ""],
      details.map((row) => row.map(String)),
      115,
    ) + 22;
  const metrics: [string, number][] = [
    ["Matching records", report.total],
    ...Object.entries(report.summary.metrics),
  ];
  const columns = Math.min(width > 700 ? 4 : 3, metrics.length);
  const cardWidth = (contentWidth - (columns - 1) * 12) / columns;
  for (let i = 0; i < metrics.length; i += columns) {
    if (y + 72 > doc.internal.pageSize.getHeight() - 40) {
      doc.addPage();
      y = 115;
    }
    metrics.slice(i, i + columns).forEach(([label, value], col) => {
      const x = margin + col * (cardWidth + 12);
      doc.setFillColor(239, 246, 249);
      doc.roundedRect(x, y, cardWidth, 64, 5, 5, "F");
      doc.setFontSize(8);
      doc.setTextColor(71, 85, 105);
      doc.setFont("helvetica", "normal");
      doc.text(doc.splitTextToSize(label, cardWidth - 20), x + 10, y + 16);
      doc.setFontSize(20);
      doc.setFont("helvetica", "bold");
      doc.setTextColor(...blue);
      doc.text(reportNumber(value), x + 10, y + 49);
    });
    y += 76;
  }
  const filters = Object.entries(report.metadata.filters).filter(
    ([key, value]) =>
      value !== undefined &&
      ![
        "category",
        "page",
        "pageSize",
        "tenantId",
        "dateFrom",
        "dateTo",
      ].includes(key),
  );
  if (filters.length)
    y =
      table(
        ["Applied filter", "Value"],
        filters.map(([k, v]) => [reportLabel(k), String(v)]),
        section("Filters", y + 4),
      ) + 24;
  if (report.summary.statuses.length)
    y =
      table(
        ["Status", "Records"],
        report.summary.statuses.map((s) => [
          reportLabel(s.status),
          reportNumber(s.count),
        ]),
        section("Status overview", y + 4),
      ) + 24;
  for (const dimension of [
    ...new Set(report.summary.breakdowns.map((b) => b.dimension)),
  ]) {
    const entries = report.summary.breakdowns.filter(
      (b) => b.dimension === dimension,
    );
    const completed = entries.some((b) => b.completed !== undefined);
    y =
      table(
        [dimension, "Records", ...(completed ? ["Completed"] : [])],
        entries.map((b) => [
          b.key,
          reportNumber(b.count),
          ...(completed
            ? [b.completed === undefined ? "-" : reportNumber(b.completed)]
            : []),
        ]),
        section(`${dimension} activity`, y + 4),
      ) + 24;
  }
  if (report.summary.amounts.length) {
    table(
      ["Currency / status", "Financial totals"],
      report.summary.amounts.map((a) => [
        `${a.currency || "Unspecified"} / ${reportLabel(String(a.status || ""))}`,
        Object.entries(a)
          .filter(([key]) => key !== "currency" && key !== "status")
          .map(
            ([key, value]) =>
              `${reportLabel(key)}: ${formatFinancialValue(value)}`,
          )
          .join("; "),
      ]),
      section("Financial summary", y + 4),
    );
  }
  doc.addPage();
  table(
    headers.map(reportLabel),
    rows.map((r) =>
      headers.map((h) =>
        typeof r[h] === "number"
          ? reportNumber(r[h] as number)
          : String(r[h] ?? ""),
      ),
    ),
    section("Detailed records", 115),
    true,
  );
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page++) {
    doc.setPage(page);
    doc.addImage(reportLogo, "PNG", margin, 22, 100, 52, "urutix-logo");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(18);
    doc.setTextColor(...blue);
    doc.text(`${title} report`, width - margin, 43, { align: "right" });
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(100, 116, 139);
    doc.text(
      page === 1 ? "Overview and performance" : "Report continuation",
      width - margin,
      62,
      { align: "right" },
    );
    doc.setDrawColor(...teal);
    doc.setLineWidth(2);
    doc.line(margin, 88, width - margin, 88);
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(
      `URUTIX | ${title} | Page ${page} of ${pages}`,
      40,
      doc.internal.pageSize.getHeight() - 15,
    );
  }
  return doc;
}

export function exportRows(
  format: ExportFormat,
  report: RoleReportResult,
  printWindow?: Window | null,
) {
  const { title, headers, rows, metadata, summary } = report;
  const base = `${report.category}-${metadata.generatedAt.slice(0, 10)}`;
  const info = reportInformation(report);
  if (format === "xlsx") {
    const safeRows = rows.map((row) =>
      Object.fromEntries(
        Object.entries(row).map(([key, value]) => {
          if (
            typeof value === "string" &&
            /^(Completed|Created|Date|Issued|Due|Paid|Start|End|PickupDate|Hired|Insurance|Roadworthy)$/.test(
              key,
            ) &&
            /^\d{4}-\d{2}-\d{2}$/.test(value)
          )
            return [key, new Date(value + "T00:00:00Z")];
          return [key, value];
        }),
      ),
    );
    const sheet = XLSX.utils.json_to_sheet(safeRows, {
      header: headers,
      cellDates: true,
      dateNF: "yyyy-mm-dd",
    });
    sheet["!autofilter"] = { ref: sheet["!ref"] || "A1" };
    sheet["!cols"] = headers.map((h) => ({
      wch: Math.min(42, Math.max(16, h.length + 4)),
    }));
    Object.entries(sheet).forEach(([address, cell]) => {
      if (!address.startsWith("!") && cell.t === "n") cell.z = "#,##0.00";
    });
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, sheet, title.slice(0, 31));
    XLSX.utils.book_append_sheet(
      wb,
      XLSX.utils.aoa_to_sheet([["Report information", "Value"], ...info]),
      "Report Summary",
    );
    if (summary.amounts.length)
      XLSX.utils.book_append_sheet(
        wb,
        XLSX.utils.json_to_sheet(
          summary.amounts.map((a) =>
            Object.fromEntries(
              Object.entries(a).map(([k, v]) => [k, financialCell(v)]),
            ),
          ),
        ),
        "Financial Totals",
      );
    if (summary.breakdowns.length)
      XLSX.utils.book_append_sheet(
        wb,
        XLSX.utils.json_to_sheet(summary.breakdowns),
        "Performance",
      );
    const summarySheet = wb.Sheets["Report Summary"];
    summarySheet["!cols"] = [{ wch: 32 }, { wch: 75 }, { wch: 4 }, { wch: 28 }];
    downloadWorkbook(wb, `${base}.xlsx`);
    return;
  }
  const doc = createReportPdf(report);
  if (format === "print") {
    doc.autoPrint();
    const url = URL.createObjectURL(doc.output("blob"));
    const tab = printWindow || window.open(url, "_blank");
    if (tab && printWindow) tab.location.href = url;
    if (!tab) {
      URL.revokeObjectURL(url);
      throw new Error("Allow pop-ups to open the print view");
    }
    setTimeout(() => URL.revokeObjectURL(url), 60000);
  } else doc.save(`${base}.pdf`);
}
